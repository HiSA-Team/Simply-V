# Build a bare-metal program for the Zynq-7000 PS (Cortex-A9 #0) with the Vitis Python API.
# Usage: vitis -s sw/host/zynq/build_ps_app.py [program]   (default program: ps_mailbox)
# Platform and BSP are generated from the Simply-V XSA; linker script and startup code come from Vitis.
# Outputs go in sw/host/zynq/<program>/bin (ignored by git).
import glob
import os
import re
import shutil
import stat
import sys

import vitis

PLATFORM = "simplyv_ps"
CPU      = "ps7_cortexa9_0"
DOMAIN   = "standalone_" + CPU
RETRIES  = 5  # Windows builds may fail at random (e.g. antivirus locking files)

# All paths are relative to this script, no absolute paths
ZYNQ_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT     = os.path.abspath(os.path.join(ZYNQ_DIR, "..", "..", ".."))
PROGRAM  = sys.argv[1] if len(sys.argv) > 1 else "ps_mailbox"
SRC_DIR  = os.path.join(ZYNQ_DIR, PROGRAM, "src")
WS_DIR   = os.path.join(ZYNQ_DIR, PROGRAM, "bin")
GEN_DIR  = os.path.join(WS_DIR, "gen")
XSA      = os.path.join(ROOT, "hw", "xilinx", "ips", "common", "xlnx_ps_wrapper", "build", "xlnx_ps_wrapper.xsa")
INC_DIRS = [os.path.join(ROOT, "sw", "SoC", "lib", "simplyv", "inc"),
            os.path.join(ROOT, "sw", "SoC", "examples", PROGRAM, "inc")]
XPFM     = os.path.join(WS_DIR, PLATFORM, "export", PLATFORM, PLATFORM + ".xpfm")
ELF      = os.path.join(WS_DIR, PROGRAM, "build", PROGRAM + ".elf")


def retry(what, func, output):
    # Vitis may report a failed build without raising: the output file is the real check
    for attempt in range(1, RETRIES + 1):
        try:
            func()
        except Exception as e:
            print(f"[BUILD_PS] {what}: attempt {attempt} raised: {e}")
        if os.path.isfile(output):
            print(f"[BUILD_PS] {what}: done (attempt {attempt})")
            return
        print(f"[BUILD_PS] {what}: attempt {attempt} failed, {output} not found")
    sys.exit(f"[BUILD_PS] ERROR: {what} failed {RETRIES} times")


def gp0_base(platform_dir):
    # M_AXI_GP0 base address, from the system device tree generated from the XSA
    for f in glob.glob(os.path.join(platform_dir, "**", "*.dts*"), recursive=True):
        with open(f) as fh:
            m = re.search(r"ps7_m_axi_gp0\s*:\s*[\w-]+@([0-9a-fA-F]+)", fh.read())
        if m:
            return "0x" + m.group(1)
    sys.exit("[BUILD_PS] ERROR: M_AXI_GP0 not found in the device tree")


for path in (XSA, SRC_DIR):
    if not os.path.exists(path):
        sys.exit(f"[BUILD_PS] ERROR: {path} not found")

# A platform left half-built by a previous run is removed and created again
if os.path.isdir(os.path.join(WS_DIR, PLATFORM)) and not os.path.isfile(XPFM):
    # Some files copied by Vitis are read-only, and Windows refuses to delete them as they are
    shutil.rmtree(os.path.join(WS_DIR, PLATFORM),
                  onexc=lambda func, path, exc: (os.chmod(path, stat.S_IWRITE), func(path)))

client = vitis.create_client()
client.set_workspace(path=WS_DIR)

# Platform and BSP: built once, then reused
if not os.path.isfile(XPFM):
    platform = client.create_platform_component(name=PLATFORM, hw_design=XSA, os="standalone",
                                                cpu=CPU, domain_name=DOMAIN, no_boot_bsp=True)
    retry("platform build", platform.build, XPFM)
print("[BUILD_PS] platform:", XPFM)

# Header with the addresses taken from the hardware description
os.makedirs(GEN_DIR, exist_ok=True)
with open(os.path.join(GEN_DIR, "ps_hw.h"), "w") as fh:
    fh.write("// Generated by build_ps_app.py from the XSA, do not edit\n")
    fh.write("#pragma once\n")
    fh.write(f"#define PS_M_AXI_GP0_BASEADDR ({gp0_base(os.path.join(WS_DIR, PLATFORM))}u)\n")

# Application: our sources and headers, the rest comes from Vitis
if os.path.isdir(os.path.join(WS_DIR, PROGRAM)):
    app = client.get_component(name=PROGRAM)
else:
    app = client.create_app_component(name=PROGRAM, platform=XPFM, domain=DOMAIN,
                                      template="empty_application")
for d in [SRC_DIR, GEN_DIR] + [d for d in INC_DIRS if os.path.isdir(d)]:
    files = [f for f in os.listdir(d) if f.endswith((".c", ".h"))]
    app.import_files(from_loc=d, files=files, dest_dir_in_cmp="src")
if os.path.isfile(ELF):
    os.remove(ELF)  # so that a stale ELF is not taken as a successful build
retry("application build", app.build, ELF)
print("[BUILD_PS] ELF:", ELF)

vitis.dispose()
